#!/usr/bin/env python3
"""Generate data/eval_results/INDEX.md — a browsable table of every tracked
measurement file: path, date, size, and which docs cite it.

Why: the docs cite ~1,500 result files under data/eval_results/ by path as
their evidence, but the directory itself had no index. This script derives
one from git, so it is regenerable and never hand-edited.

Date = the YYYYMMDD / YYYY-MM-DD token in the file name when present,
otherwise the file's first commit date. "Cited by" = every tracked Markdown or
text doc (docs/, spike/, scripts/, .claude/, README.md) whose text contains the
file's base name; "-" means nothing cites it (campaign scratch, per
data/eval_results/README.md).

Usage (from the repo root, with the venv):
    .venv/bin/python3 scripts/repo_tools/build_eval_results_index.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ROOT = "data/eval_results"
OUT = REPO / ROOT / "INDEX.md"
DATE_RE = re.compile(r"(20\d{2})[-_]?(\d{2})[-_]?(\d{2})")


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True,
                          capture_output=True, text=True).stdout


def tracked(prefix: str) -> list[str]:
    return [p for p in git("ls-files", "--", prefix).split("\n") if p]


def first_commit_dates(paths: list[str]) -> dict[str, str]:
    out: dict[str, str] = {}
    log = git("log", "--reverse", "--format=@@%cs", "--name-only", "--", ROOT)
    cur = ""
    for line in log.split("\n"):
        if line.startswith("@@"):
            cur = line[2:]
        elif line and line not in out:
            out[line] = cur
    return out


def name_date(name: str) -> str | None:
    m = DATE_RE.search(name)
    if not m:
        return None
    y, mo, d = (int(x) for x in m.groups())
    try:
        return date(y, mo, d).isoformat()
    except ValueError:
        return None


def citations(files: list[str]) -> dict[str, list[str]]:
    """A doc cites a file when it contains the file's base name, provided that
    base name is unique across the whole tracked tree; ambiguous names
    (README.md, manifest.json, ...) only count when the doc spells the path
    under eval_results/."""
    docs = [p for p in git("ls-files", "--", "docs", "spike", "scripts", ".claude", "README.md").split("\n")
            if p.endswith((".md", ".txt"))]
    repo_bases: dict[str, int] = defaultdict(int)
    for p in git("ls-files").split("\n"):
        if p:
            repo_bases[Path(p).name] += 1
    token_to_paths: dict[str, list[str]] = defaultdict(list)
    for f in files:
        base = Path(f).name
        token = base if repo_bases[base] == 1 else "eval_results/" + f[len(ROOT) + 1:]
        token_to_paths[token].append(f)
    cited: dict[str, set[str]] = defaultdict(set)
    tokens = sorted(token_to_paths, key=len, reverse=True)
    token_re = re.compile("|".join(re.escape(t) for t in tokens)) if tokens else None
    for d in docs:
        try:
            text = (REPO / d).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if token_re is None:
            continue
        for m in set(token_re.findall(text)):
            for f in token_to_paths[m]:
                cited[f].add(d)
    return {f: sorted(v) for f, v in cited.items()}


def size_of(p: str) -> str:
    try:
        n = (REPO / p).stat().st_size
    except OSError:
        return "?"
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return "?"


def main() -> int:
    files = [p for p in tracked(ROOT) if p != f"{ROOT}/INDEX.md"]
    commit_dates = first_commit_dates(files)
    cites = citations(files)
    groups: dict[str, list[str]] = defaultdict(list)
    for f in files:
        rel = f[len(ROOT) + 1:]
        groups[rel.rsplit("/", 1)[0] + "/" if "/" in rel else "(top level)"].append(f)
    n_cited = sum(1 for f in files if f in cites)
    lines = [
        "# data/eval_results/ — evidence index (generated)",
        "",
        "**Status:** ACTIVE (regenerated by `scripts/repo_tools/build_eval_results_index.py`; do not hand-edit)",
        "",
        f"Generated {date.today().isoformat()} from git: {len(files)} tracked files, "
        f"{n_cited} cited by at least one doc, {len(files) - n_cited} uncited (campaign scratch — see `README.md`).",
        "Date = the date token in the file name, else the first commit date. Conventions: `README.md`.",
        "",
    ]
    for group in sorted(groups, key=lambda g: (g != "(top level)", g)):
        rows = sorted(groups[group])
        lines += [f"## {group} ({len(rows)} files)", "", "| File | Date | Size | Cited by |", "|---|---|---|---|"]
        for f in rows:
            name = f[len(ROOT) + 1:]
            d = name_date(Path(f).name) or commit_dates.get(f, "?")
            c = ", ".join(f"`{x}`" for x in cites.get(f, [])) or "-"
            lines.append(f"| `{name}` | {d} | {size_of(f)} | {c} |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(files)} files, {n_cited} cited")
    return 0


if __name__ == "__main__":
    sys.exit(main())
