#!/usr/bin/env python3
"""Build-time helper for the portable Linux runtime bundle.

Subcommands (all driven by ``build_linux_runtime.sh``; see
``docs/infrastructure/PORTABLE_LINUX_BUNDLE.md``):

``lock``
    Resolve ``serving_requirements_linux.in`` (top-level pins) into a fully
    pinned, hash-locked ``serving_requirements_linux.lock.txt`` with the
    bundle's own python (``pip install --dry-run --report``). Run by a human
    when a pin changes; the build only ever installs from the lock.

``snapshot``
    Write the sorted list of files under a directory (the freshly extracted
    CPython) so ``manifest`` can split runtime bytes from wheel bytes.

``fix-scripts``
    Rewrite pip console scripts whose shebang names the absolute build path
    into the ``/bin/sh`` trampoline form, so they stay relocatable and the
    bundle's bytes do not depend on where it was built.

``manifest``
    Emit ``BUNDLE_MANIFEST.json``: every file's relative path, sha256 and byte
    size, a category (runtime / wheels / seismic_so / source / launcher),
    per-category totals, and one ``bundle_sha256`` fingerprint over the sorted
    entries, so two builds can be compared with a single string.

Only the standard library is used, so any python3 can run it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

EXCLUDED_TOP = {"BUNDLE_MANIFEST.json", "BUILD_REPORT.json"}
TRAMPOLINE = (
    "#!/bin/sh\n"
    "'''exec' \"$(dirname -- \"$(realpath -- \"$0\")\")/python3.11\" \"$0\" \"$@\"\n"
    "' '''\n"
)


def _sha256(path: Path) -> str:
    """Stream a file through sha256."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _sha256_url(url: str) -> str:
    """sha256 of a remote file, for index entries that publish no hash."""
    import urllib.request
    h = hashlib.sha256()
    with urllib.request.urlopen(url, timeout=120) as resp:
        for chunk in iter(lambda: resp.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _walk(root: Path):
    """Yield (relative posix path, Path) for every file or symlink, sorted."""
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        d = Path(dirpath)
        for name in filenames:
            p = d / name
            out.append((p.relative_to(root).as_posix(), p))
        for name in dirnames:
            p = d / name
            if p.is_symlink():
                out.append((p.relative_to(root).as_posix(), p))
    out.sort(key=lambda t: t[0])
    return out


def cmd_lock(args: argparse.Namespace) -> int:
    """Resolve the top-level pins into a sha256-locked requirement file."""
    with tempfile.TemporaryDirectory() as td:
        report = Path(td) / "report.json"
        cmd = [
            args.python, "-m", "pip", "install", "--dry-run", "--ignore-installed",
            "--only-binary=:all:", "--disable-pip-version-check", "--quiet",
            "--index-url", args.pypi_index, "--extra-index-url", args.torch_index,
            "--report", str(report), "-r", args.infile,
        ]
        subprocess.run(cmd, check=True, env={**os.environ, "PYTHONNOUSERSITE": "1"})
        data = json.loads(report.read_text())
    lines = []
    for item in data["install"]:
        meta = item["metadata"]
        hashes = item["download_info"].get("archive_info", {}).get("hashes", {})
        url = item["download_info"]["url"]
        sha = hashes.get("sha256") or _sha256_url(url)
        lines.append((meta["name"].lower(), meta["version"], sha, url.rsplit("/", 1)[-1]))
    lines.sort()
    header = [
        "# GENERATED by scripts/portable_linux/bundle_tool.py lock -- do not edit by hand.",
        f"# Source: {Path(args.infile).name}; resolver python: {args.python_label}.",
        "# Every wheel is pinned by version AND sha256; the build installs with",
        "# --require-hashes --no-deps --only-binary=:all: from this file only.",
        "",
    ]
    body = [f"{n}=={v} \\\n    --hash=sha256:{s}\n    # {w}" for n, v, s, w in lines]
    Path(args.out).write_text("\n".join(header) + "\n".join(body) + "\n")
    print(json.dumps({"locked": len(lines), "out": args.out}))
    return 0


def cmd_snapshot(args: argparse.Namespace) -> int:
    """Record the file list of a directory tree."""
    root = Path(args.root)
    rels = [rel for rel, _ in _walk(root)]
    Path(args.out).write_text("\n".join(rels) + "\n")
    print(json.dumps({"files": len(rels), "out": args.out}))
    return 0


def cmd_fix_scripts(args: argparse.Namespace) -> int:
    """Replace absolute-path shebangs under a bin dir with the sh trampoline."""
    bindir = Path(args.bin)
    build_root = str(Path(args.build_root).resolve())
    fixed = []
    for p in sorted(bindir.iterdir()):
        if p.is_symlink() or not p.is_file():
            continue
        raw = p.read_bytes()
        if not raw.startswith(b"#!"):
            continue
        first, _, rest = raw.partition(b"\n")
        if build_root.encode() not in first:
            continue
        p.write_bytes(TRAMPOLINE.encode() + rest)
        fixed.append(p.name)
    records = _rewrite_records(Path(args.site), bindir, set(fixed))
    print(json.dumps({"fixed_scripts": fixed, "records_updated": records}))
    return 0


def _rewrite_records(site: Path, bindir: Path, names: set[str]) -> int:
    """Refresh dist-info RECORD rows for rewritten scripts (hash + size)."""
    import base64
    updated = 0
    for record in sorted(site.glob("*.dist-info/RECORD")):
        rows = record.read_text().splitlines()
        changed = False
        for i, row in enumerate(rows):
            path, _, _ = row.partition(",")
            name = path.rsplit("/", 1)[-1]
            if name in names and path.startswith("../../../bin/"):
                data = (bindir / name).read_bytes()
                digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=")
                rows[i] = f"{path},sha256={digest.decode()},{len(data)}"
                changed = True
        if changed:
            record.write_text("\n".join(rows) + "\n")
            updated += 1
    return updated


def _category(rel: str, baseline: set[str]) -> str:
    """Map a bundle-relative path to its size-split category."""
    if rel == "python/lib/python3.11/site-packages/sfu_bundle.pth":
        return "launcher"
    if rel.startswith("python/"):
        return "runtime" if rel[len("python/"):] in baseline else "wheels"
    if rel.startswith("ext/"):
        return "seismic_so"
    if rel.startswith("app/"):
        return "source"
    return "launcher"


def cmd_manifest(args: argparse.Namespace) -> int:
    """Hash every file in the bundle and write the bundle manifest."""
    root = Path(args.root)
    baseline = set(Path(args.baseline).read_text().split())
    entries = []
    totals: dict[str, dict[str, int]] = {}
    for rel, p in _walk(root):
        if rel in EXCLUDED_TOP:
            continue
        cat = _category(rel, baseline)
        if p.is_symlink():
            entries.append({"path": rel, "symlink": os.readlink(p), "category": cat})
            continue
        size = p.stat().st_size
        entries.append({"path": rel, "sha256": _sha256(p), "bytes": size, "category": cat})
        t = totals.setdefault(cat, {"files": 0, "bytes": 0})
        t["files"] += 1
        t["bytes"] += size
    fp = hashlib.sha256()
    for e in entries:
        fp.update(f"{e['path']}\t{e.get('sha256', '')}\t{e.get('bytes', '')}\t"
                  f"{e.get('symlink', '')}\n".encode())
    meta = json.loads(args.meta) if args.meta else {}
    manifest = {
        "schema": "sfu_portable_linux_bundle_manifest/1",
        **meta,
        "excludes": ["index data", "model weights", "BUNDLE_MANIFEST.json", "BUILD_REPORT.json"],
        "totals": {k: totals[k] for k in sorted(totals)},
        "total_bytes": sum(t["bytes"] for t in totals.values()),
        "n_files": sum(t["files"] for t in totals.values()),
        "bundle_sha256": fp.hexdigest(),
        "files": entries,
    }
    Path(args.out).write_text(json.dumps(manifest, indent=1, sort_keys=False) + "\n")
    print(json.dumps({"bundle_sha256": manifest["bundle_sha256"],
                      "total_bytes": manifest["total_bytes"],
                      "totals": manifest["totals"]}))
    return 0


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("lock")
    p.add_argument("--python", required=True)
    p.add_argument("--python-label", default="python-build-standalone")
    p.add_argument("--infile", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--pypi-index", required=True)
    p.add_argument("--torch-index", required=True)
    p.set_defaults(fn=cmd_lock)

    p = sub.add_parser("snapshot")
    p.add_argument("--root", required=True)
    p.add_argument("--out", required=True)
    p.set_defaults(fn=cmd_snapshot)

    p = sub.add_parser("fix-scripts")
    p.add_argument("--bin", required=True)
    p.add_argument("--build-root", required=True)
    p.add_argument("--site", required=True)
    p.set_defaults(fn=cmd_fix_scripts)

    p = sub.add_parser("manifest")
    p.add_argument("--root", required=True)
    p.add_argument("--baseline", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--meta", default="")
    p.set_defaults(fn=cmd_manifest)

    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
