#!/usr/bin/env python3
"""Phase 5b-prep — stage the Windows build kit into the bundle.

The seismic engine (`seismic.pyd`) must be compiled natively on Windows (pyo3
cross-compile can't be runtime-validated on Linux; design §7). This makes that
build TURNKEY and OFFLINE for the Rust half: it copies the fork source into the
bundle and **vendors** every crates.io + git dependency, so the Windows box needs
only a Rust toolchain (no fragile network git fetches — notably the `fixed` dep
whose upstream rev was force-pushed away; the vendored copy pins it).

Produces:

    $BUNDLE/
      build_windows_runtime.ps1            (the on-Windows build entry point)
      build/
        seismic_upstream/  (+ .cargo/config.toml -> vendored-sources, + Cargo.lock)
        vectorium_fork/  toolkit_fork/      (path deps, siblings)
        seismic_upstream/vendor/            (all crates.io + git deps, offline)
        serving_requirements_win.txt

On Linux this is fully runnable (source copy + `cargo vendor`, which resolves
online once). The COMPILE happens later via build_windows_runtime.ps1 on Windows.

    .venv/bin/python3 scripts/portable_socsci/06_windows_buildkit.py

Env: BUNDLE (default /var/tmp/portable_socsci_bundle).
"""
import json
import os
import shutil
import subprocess
import time

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BUNDLE = os.environ.get("BUNDLE", "/var/tmp/portable_socsci_bundle")
SPIKE = os.path.join(REPO, "spike")
WIN = os.path.join(REPO, "scripts", "portable_socsci", "windows")

BUILD = os.path.join(BUNDLE, "build")
FORKS = ["seismic_upstream", "vectorium_fork", "toolkit_fork"]
IGNORE = shutil.ignore_patterns("target", ".git", "data", "__pycache__",
                                "*.pyc", "vendor", "*.mmap")


def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def _du(path):
    total = 0
    for root, _dirs, files in os.walk(path):
        for fn in files:
            try:
                total += os.path.getsize(os.path.join(root, fn))
            except OSError:
                pass
    return total


def copy_forks():
    os.makedirs(BUILD, exist_ok=True)
    for fork in FORKS:
        src = os.path.join(SPIKE, fork)
        dst = os.path.join(BUILD, fork)
        if not os.path.isdir(src):
            raise SystemExit(f"missing fork source: {src}")
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        log(f"copying fork source {fork} (source only, no target/data)...")
        shutil.copytree(src, dst, ignore=IGNORE)
    lock = os.path.join(BUILD, "seismic_upstream", "Cargo.lock")
    if not os.path.isfile(lock):
        shutil.copy2(os.path.join(SPIKE, "seismic_upstream", "Cargo.lock"), lock)


def vendor_deps():
    """`cargo vendor` in the copied fork → offline crates.io + git deps.

    Resolves online once (needs the live `fixed` branch HEAD, already re-pinned in
    Cargo.lock). Writes the [source] replacement into .cargo/config.toml so the
    Windows build is fully offline."""
    fork = os.path.join(BUILD, "seismic_upstream")
    log("cargo vendor (downloads all deps' source into build/seismic_upstream/vendor)...")
    res = subprocess.run(
        ["cargo", "vendor", "vendor"], cwd=fork,
        capture_output=True, text=True)
    if res.returncode != 0:
        raise SystemExit(f"cargo vendor failed:\n{res.stderr[-2000:]}")
    cargo_dir = os.path.join(fork, ".cargo")
    os.makedirs(cargo_dir, exist_ok=True)
    with open(os.path.join(cargo_dir, "config.toml"), "w") as f:
        f.write("# Generated by 06_windows_buildkit.py (cargo vendor) — offline "
                "Rust build for the portable social-sciences Windows bundle.\n")
        f.write(res.stdout)
    return _du(os.path.join(fork, "vendor"))


def stage_kit_files():
    shutil.copy2(os.path.join(WIN, "build_windows_runtime.ps1"),
                 os.path.join(BUNDLE, "build_windows_runtime.ps1"))
    shutil.copy2(os.path.join(WIN, "serving_requirements_win.txt"),
                 os.path.join(BUILD, "serving_requirements_win.txt"))


def main():
    t0 = time.time()
    copy_forks()
    vendor_bytes = vendor_deps()
    stage_kit_files()
    report = {
        "bundle": BUNDLE,
        "build_dir": BUILD,
        "forks": {f: round(_du(os.path.join(BUILD, f)) / 2**20, 1)
                  for f in FORKS},
        "vendor_mib": round(vendor_bytes / 2**20, 1),
        "build_total_mib": round(_du(BUILD) / 2**20, 1),
        "ps1": os.path.join(BUNDLE, "build_windows_runtime.ps1"),
        "total_seconds": round(time.time() - t0, 1),
        "next": "run build_windows_runtime.ps1 on a Windows host (Rust required)",
    }
    print(json.dumps(report, indent=2), flush=True)
    with open(os.path.join(BUNDLE, "_windows_buildkit_report.json"), "w") as f:
        json.dump(report, f, indent=2)
    log("BUILD KIT STAGED. seismic.pyd + python\\ are produced on Windows by "
        "build_windows_runtime.ps1.")


if __name__ == "__main__":
    main()
